export function formatPrice(n) {
  return n.toLocaleString('th-TH') + ' บาท'
}

export function getProduct(id) {
  return PRODUCTS.find((p) => p.id === id)
}

// สถานะสต็อก: 'in' = มีสินค้า (รู้จำนวน) | 'out' = สินค้าหมด | 'unknown' = ไม่ทราบจำนวน (ไม่ล็อกจำนวน)
export function stockStatus(p) {
  if (typeof p.stock === 'number') return p.stock > 0 ? 'in' : 'out'
  return 'unknown'
}

export function statusText(p) {
  const s = stockStatus(p)
  if (s === 'in') return 'มีสินค้า'
  if (s === 'out') return 'สินค้าหมด'
  return 'มีสินค้า'
}

// ตรวจว่าสินค้าในตะกร้า + ที่จะเพิ่ม เกินสต็อกหรือไม่ (เฉพาะสินค้าที่รู้จำนวน)
export function checkStock(p, inCartQty, addQty) {
  if (typeof p.stock !== 'number') return { ok: true }
  if (p.stock <= 0) return { ok: false, message: 'สินค้าหมด' }
  if (inCartQty + addQty > p.stock) {
    return { ok: false, message: `เพิ่มได้สูงสุด ${p.stock} ชิ้น (คงเหลือ ${p.stock} ชิ้น)` }
  }
  return { ok: true }
}

// สินค้าแนะนำ: สินค้าอื่นที่ไม่ใช่ชิ้นปัจจุบัน (สูงสุด 3 รายการ)
export function getRelated(id, count = 3) {
  return PRODUCTS.filter((p) => p.id !== id).slice(0, count)
}
